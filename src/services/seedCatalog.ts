function makeArtDataUri(title: string, c1: string, c2: string, accent: string): string {
  const safe = title.replace(/[<>&"']/g, '').slice(0, 18);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${c1}"/><stop offset="100%" stop-color="${c2}"/></linearGradient></defs><rect width="400" height="400" fill="url(#g)"/><circle cx="290" cy="110" r="95" fill="${accent}" opacity="0.28"/><circle cx="130" cy="290" r="120" fill="#000" opacity="0.18"/><text x="28" y="348" fill="#fff7ee" font-family="system-ui,sans-serif" font-size="24" font-weight="700" opacity="0.92">${safe}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

